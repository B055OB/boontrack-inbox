/**
 * lib/outbox/worker.ts
 * Transactional Outbox Worker Engine — Sprint P1
 *
 * Implements the full pipeline:
 *   1. Claim a batch of PENDING messages atomically via FOR UPDATE SKIP LOCKED
 *      (executed inside a Postgres function called via supabase.rpc)
 *   2. For each message: dispatch via IProviderAdapter
 *   3. On success  → mark SENT
 *   4. On failure  → jittered exponential backoff, retry or escalate to DEAD_LETTER
 *
 * Concurrency safety: Multiple worker instances can run in parallel.
 * FOR UPDATE SKIP LOCKED in claim_outbox_batch() ensures each message is
 * claimed by exactly one worker — no double-processing.
 */

import { getSupabaseAdmin, getSupabase } from '@/lib/supabaseClient';
import type { IProviderAdapter, OutboxMessage, OutboxRunSummary } from './types';
import { multiProviderAdapter } from './adapters/multi-provider-adapter';
import { getRuntimeSessionCache } from '@/lib/whatsapp/bot-control-service';
import { toCanonicalPhone } from '@/lib/whatsapp/outbound-registry';
import { cleanCustomerPhone } from '@/lib/whatsapp/inbox-persistence';

// ---------------------------------------------------------------------------
// Jittered Exponential Backoff
// ---------------------------------------------------------------------------

/**
 * Calculate a jittered backoff delay in milliseconds.
 *
 * Formula: uniform random in [0, min(maxDelayMs, baseMs * 2^retryCount)]
 *
 * @param retryCount  - Current retry attempt (0-indexed)
 * @param baseMs      - Base delay in ms (default 2000)
 * @param maxDelayMs  - Cap for the delay in ms (default 30000)
 * @returns           - Delay in milliseconds (integer)
 */
export function jitteredBackoff(
  retryCount: number,
  baseMs = 2_000,
  maxDelayMs = 30_000
): number {
  const exponential = baseMs * Math.pow(2, retryCount);
  const cap = Math.min(maxDelayMs, exponential);
  return Math.floor(Math.random() * cap);
}

/**
 * OutboxDbClient defines only the RPC surface that the worker actually uses.
 * Accepting this interface instead of the full SupabaseClient type allows tests
 * to inject a plain mock object without TypeScript structural incompatibility.
 */
export interface OutboxDbClient {
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  rpc(fn: string, args?: Record<string, unknown>): Promise<{ data: any; error: { message: string } | null }>;
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  from?(tableName: string): any;
}

// eslint-disable-next-line @typescript-eslint/no-unused-vars
type SupabaseAdminClient = OutboxDbClient;

/**
 * Claim a batch of PENDING outbox messages atomically.
 * Delegates to the claim_outbox_batch() Postgres function which uses
 * FOR UPDATE SKIP LOCKED to prevent double-processing across parallel workers.
 */
async function claimBatch(
  db: SupabaseAdminClient,
  batchSize = 10
): Promise<OutboxMessage[]> {
  const { data, error } = await db.rpc('claim_outbox_batch', {
    batch_size: batchSize,
  });

  if (error) {
    throw new Error(`[OutboxWorker] claimBatch RPC failed: ${error.message}`);
  }

  return (data as OutboxMessage[]) ?? [];
}

/**
 * Mark a message as SENT.
 */
async function markSent(
  db: SupabaseAdminClient,
  id: string,
  messageId?: string
): Promise<void> {
  const { error } = await db.rpc('mark_outbox_sent', {
    p_id: id,
    p_message_id: messageId ?? null,
  });
  if (error) {
    console.error(`[OutboxWorker] markSent failed for id=${id}:`, error.message);
  }
}

/**
 * Mark a message for retry (or escalate to DEAD_LETTER if max retries reached).
 * The DB function handles the retry_count >= max_retries check atomically.
 */
async function markRetry(
  db: SupabaseAdminClient,
  id: string,
  errorMsg: string,
  delayMs: number
): Promise<void> {
  const { error } = await db.rpc('mark_outbox_retry', {
    p_id: id,
    p_error: errorMsg,
    p_delay_ms: delayMs,
  });
  if (error) {
    console.error(`[OutboxWorker] markRetry failed for id=${id}:`, error.message);
  }
}


/**
 * Detects whether an outbox message is generated by / destined for an AI Bot.
 */
export function isAiOutboxMessage(message: OutboxMessage): boolean {
  const p = (message.payload || {}) as Record<string, any>;
  if (p.is_ai === false || p.transactional === true || p.category === 'fulfillment') {
    return false;
  }
  return Boolean(
    p.is_ai === true ||
    p.is_ai === 'true' ||
    p.source === 'ai' ||
    p.source === 'bot' ||
    p.source === 'llm' ||
    p.sender_type === 'bot' ||
    p.sender_type === 'ai' ||
    p.type === 'ai_response' ||
    p.type === 'bot_reply' ||
    p.requires_bot_active === true ||
    p.control_version !== undefined ||
    (message as any).is_ai === true ||
    (message as any).source === 'ai' ||
    (message as any).source === 'bot' ||
    (message as any).control_version !== undefined
  );
}

/**
 * Mark a message as SUPPRESSED when paused or unverified (Fail-Closed).
 */
export async function markSuppressed(
  db: SupabaseAdminClient,
  id: string,
  reason: string
): Promise<void> {
  // 1. Try dedicated RPC
  try {
    const { error } = await db.rpc('mark_outbox_suppressed', {
      p_id: id,
      p_reason: reason,
    });
    if (!error) return;
  } catch (_) {}

  // 2. Try direct table update
  if (typeof (db as any).from === 'function') {
    try {
      const nowIso = new Date().toISOString();
      await (db as any).from('message_outbox').update({
        status: 'SUPPRESSED',
        last_error: `[SUPPRESSED] ${reason}`,
        error_log: `[SUPPRESSED] ${reason}`,
        failed_at: nowIso,
        updated_at: nowIso,
      }).eq('id', id);
      return;
    } catch (_) {}
  }

  // 3. Fallback to mark_outbox_retry with error message
  try {
    await db.rpc('mark_outbox_retry', {
      p_id: id,
      p_error: `[SUPPRESSED] ${reason}`,
      p_delay_ms: 0,
    });
  } catch (err: any) {
    console.error(`[OutboxWorker] markSuppressed failed for id=${id}:`, err?.message || err);
  }
}

/**
 * Final Dispatch Gate: Pre-dispatch status & circuit breaker verification.
 * Verifies tenant active, contact permitted, and control version monotonic safety.
 * FAIL-CLOSED: Suppresses outbound if status cannot be verified or DB/Redis fails.
 */
export async function verifyBotDispatchGate(
  db: SupabaseAdminClient,
  message: OutboxMessage
): Promise<{ allowed: boolean; reason: string }> {
  const tenantId = message.tenant_id;
  const rawRecipient = message.recipient_phone || message.recipient || '';
  const recipientPhone = toCanonicalPhone(rawRecipient) || cleanCustomerPhone(rawRecipient) || rawRecipient;
  const payload = (message.payload || {}) as Record<string, any>;
  const jobControlVersion = payload.control_version ?? (message as any).control_version;

  try {
    // 1. Fast Circuit Breaker: In-memory runtime session & tenant cache
    const cachedGlobal = getRuntimeSessionCache(tenantId);
    if (cachedGlobal) {
      if (cachedGlobal.isPaused) {
        return { allowed: false, reason: 'TENANT_GLOBAL_PAUSED_CACHE' };
      }
      if (jobControlVersion !== undefined && cachedGlobal.version !== undefined && cachedGlobal.version > jobControlVersion) {
        return { allowed: false, reason: `CONTROL_VERSION_CHANGED (job: ${jobControlVersion}, current: ${cachedGlobal.version})` };
      }
    }

    if (recipientPhone) {
      const cachedSession = getRuntimeSessionCache(tenantId, recipientPhone);
      if (cachedSession) {
        if (cachedSession.isPaused) {
          return { allowed: false, reason: 'SESSION_PAUSED_CACHE' };
        }
        if (jobControlVersion !== undefined && cachedSession.version !== undefined && cachedSession.version > jobControlVersion) {
          return { allowed: false, reason: `CONTROL_VERSION_CHANGED (job: ${jobControlVersion}, current: ${cachedSession.version})` };
        }
      }
    }

    // 2. Database Verification (Fail-Closed)
    const supabase: any = typeof (db as any).from === 'function' ? db : (getSupabaseAdmin() || getSupabase());
    if (!supabase || typeof supabase.from !== 'function') {
      return { allowed: false, reason: 'FAIL_CLOSED_NO_DATABASE_CLIENT' };
    }

    // A. Check Tenant Active & Not Bot Paused
    const { data: tenantRow, error: tenantErr } = await supabase
      .from('tenants')
      .select('id, slug, bot_paused, is_bot_active, metadata')
      .or(`id.eq.${tenantId},slug.eq.${tenantId}`)
      .maybeSingle();

    if (tenantErr) {
      return { allowed: false, reason: `FAIL_CLOSED_TENANT_DB_ERROR: ${tenantErr.message || tenantErr}` };
    }

    if (!tenantRow) {
      return { allowed: false, reason: 'FAIL_CLOSED_TENANT_NOT_FOUND' };
    }

    const isTenantPaused =
      tenantRow.bot_paused === true ||
      tenantRow.is_bot_active === false ||
      tenantRow.metadata?.bot_paused === true ||
      tenantRow.metadata?.is_bot_paused === true ||
      tenantRow.metadata?.is_bot_active === false;

    if (isTenantPaused) {
      return { allowed: false, reason: 'TENANT_BOT_PAUSED' };
    }

    // B. Check Contact Permission (conversation_sessions & conversations)
    if (recipientPhone) {
      const canonicalPhone = toCanonicalPhone(recipientPhone);
      const phoneVariants = Array.from(new Set([recipientPhone, canonicalPhone, cleanCustomerPhone(recipientPhone)])).filter(Boolean);

      // Check conversation_sessions
      const sessRes = await supabase
        .from('conversation_sessions')
        .select('session_id, is_paused, current_state, bot_status, paused_until, metadata')
        .or(`tenant_id.eq.${tenantId},tenant_id.eq.${tenantRow.id}`)
        .in('user_identifier', phoneVariants)
        .limit(5);

      if (sessRes?.error) {
        return { allowed: false, reason: `FAIL_CLOSED_SESSION_DB_ERROR: ${sessRes.error.message || sessRes.error}` };
      }

      const sessions = sessRes?.data;
      if (Array.isArray(sessions) && sessions.length > 0) {
        for (const s of sessions) {
          const isPaused =
            s.is_paused === true ||
            s.current_state === 'HUMAN_PAUSED' ||
            s.current_state === 'PAUSED' ||
            s.current_state === 'HANDOVER_TO_HUMAN' ||
            s.bot_status === 'HUMAN_PAUSED' ||
            Boolean(s.metadata?.is_bot_paused);

          if (isPaused) {
            if (s.paused_until) {
              const until = new Date(s.paused_until).getTime();
              if (!isNaN(until) && until > Date.now()) {
                return { allowed: false, reason: 'CONTACT_SESSION_PAUSED' };
              }
            } else {
              return { allowed: false, reason: 'CONTACT_SESSION_PAUSED' };
            }
          }
        }
      }

      // Check conversations
      const convRes = await supabase
        .from('conversations')
        .select('id, bot_paused, is_paused, is_bot_paused, is_bot_active, bot_mode, status')
        .or(`tenant_id.eq.${tenantId},tenant_id.eq.${tenantRow.id}`)
        .in('customer_phone', phoneVariants)
        .limit(5);

      if (convRes?.error) {
        return { allowed: false, reason: `FAIL_CLOSED_CONVERSATION_DB_ERROR: ${convRes.error.message || convRes.error}` };
      }

      const convs = convRes?.data;
      if (Array.isArray(convs) && convs.length > 0) {
        for (const c of convs) {
          const isConvPaused =
            c.bot_paused === true ||
            c.is_paused === true ||
            c.is_bot_paused === true ||
            c.is_bot_active === false ||
            c.bot_mode === 'HUMAN_ACTIVE' ||
            c.status === 'HUMAN_PAUSED' ||
            c.status === 'paused' ||
            c.status === 'human_takeover';

          if (isConvPaused) {
            return { allowed: false, reason: 'CONTACT_CONVERSATION_PAUSED' };
          }
        }
      }
    }

    return { allowed: true, reason: 'GATE_VERIFIED_ACTIVE' };
  } catch (err: any) {
    return { allowed: false, reason: `FAIL_CLOSED_EXCEPTION: ${err?.message || err}` };
  }
}

// ---------------------------------------------------------------------------
// Per-Message Processor
// ---------------------------------------------------------------------------

interface ProcessResult {
  outcome: 'sent' | 'retried' | 'dead_lettered' | 'suppressed';
}

/**
 * Process a single outbox message:
 *   1. Send via adapter
 *   2. On success: mark SENT
 *   3. On failure: calculate jittered backoff, then mark for retry or DLQ
 */
async function processMessage(
  db: SupabaseAdminClient,
  message: OutboxMessage,
  adapter: IProviderAdapter
): Promise<ProcessResult> {
  // FINAL DISPATCH GATE: Pre-dispatch status & circuit breaker verification
  if (isAiOutboxMessage(message)) {
    const gateCheck = await verifyBotDispatchGate(db, message);
    if (!gateCheck.allowed) {
      console.warn(`[OutboxWorker Gate] AI Outbound SUPPRESSED for message id=${message.id} (${gateCheck.reason})`);
      await markSuppressed(db, message.id, gateCheck.reason);
      return { outcome: 'suppressed' };
    }
  }

  let sendResult;

  try {
    sendResult = await adapter.send(message);
  } catch (err: unknown) {
    // Adapter threw instead of returning SendResult — treat as transient failure
    const msg = err instanceof Error ? err.message : String(err);
    sendResult = { success: false, error: `[adapter.send] Uncaught exception: ${msg}` };
  }

  if (sendResult.success) {
    await markSent(db, message.id, sendResult.messageId);
    return { outcome: 'sent' };
  }

  // Failure path: calculate jitter delay based on *current* retry_count
  const delayMs = jitteredBackoff(message.retry_count);
  const errorText = sendResult.error ?? 'Unknown send error';

  await markRetry(db, message.id, errorText, delayMs);

  // Determine what the DB just did (retry or DLQ) for summary reporting
  const willBeDeadLetter = message.retry_count + 1 >= message.max_retries;
  return { outcome: willBeDeadLetter ? 'dead_lettered' : 'retried' };
}

// ---------------------------------------------------------------------------
// Worker Class
// ---------------------------------------------------------------------------

export class OutboxWorker {
  private readonly batchSize: number;
  private readonly baseDelayMs: number;
  private readonly maxDelayMs: number;

  constructor(options: {
    batchSize?: number;
    baseDelayMs?: number;
    maxDelayMs?: number;
  } = {}) {
    this.batchSize = options.batchSize ?? 10;
    this.baseDelayMs = options.baseDelayMs ?? 2_000;
    this.maxDelayMs = options.maxDelayMs ?? 30_000;
  }

  /**
   * Run one worker cycle:
   *   1. Claim a batch of PENDING messages (atomically, skip-locked)
   *   2. Process each message concurrently within the batch
   *   3. Return a summary of outcomes
   *
   * Multiple calls to runOnce() can run concurrently (different Node.js
   * processes or async tasks) — the DB-level locking guarantees isolation.
   *
   * @param adapter - Provider adapter (defaults to WabaProviderAdapter in production)
   * @param db      - Supabase admin client (injectable for testing)
   */
  async runOnce(
    adapter?: IProviderAdapter,
    db?: OutboxDbClient
  ): Promise<OutboxRunSummary> {
    const effectiveAdapter = adapter ?? multiProviderAdapter;
    const client: OutboxDbClient = db ?? (getSupabaseAdmin() as unknown as OutboxDbClient);
    const summary: OutboxRunSummary = {
      claimed: 0,
      sent: 0,
      delivered: 0,
      retried: 0,
      dead_lettered: 0,
      failed: 0,
      suppressed: 0,
    };

    let batch: OutboxMessage[];
    try {
      batch = await claimBatch(client, this.batchSize);
    } catch (err: unknown) {
      const msg = err instanceof Error ? err.message : String(err);
      console.error('[OutboxWorker] Failed to claim batch:', msg);
      return summary;
    }

    summary.claimed = batch.length;

    if (batch.length === 0) {
      return summary;
    }

    // Process all messages in the batch concurrently
    const results = await Promise.allSettled(
      batch.map((msg) => processMessage(client, msg, effectiveAdapter))
    );

    for (const result of results) {
      if (result.status === 'fulfilled') {
        const { outcome } = result.value;
        if (outcome === 'sent') {
          summary.sent++;
          summary.delivered = (summary.delivered ?? 0) + 1;
        } else if (outcome === 'retried') {
          summary.retried++;
        } else if (outcome === 'dead_lettered') {
          summary.dead_lettered++;
          summary.failed = (summary.failed ?? 0) + 1;
        } else if (outcome === 'suppressed') {
          summary.suppressed = (summary.suppressed ?? 0) + 1;
        }
      } else {
        // processMessage itself should never reject, but be defensive
        console.error('[OutboxWorker] processMessage rejected:', result.reason);
        summary.retried++; // count as a failure requiring retry
      }
    }

    return summary;
  }
}

